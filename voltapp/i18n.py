def t(language: str, key: str, **kwargs) -> str:
    text = TRANSLATIONS.get(language, TRANSLATIONS["en"]).get(key, key)
    if kwargs:
        try:
            return text.format(**kwargs)
        except Exception:
            return text
    return text


