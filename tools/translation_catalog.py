#!/usr/bin/env python3
"""Export the SourceDock string catalog for translators.

SourceDock keeps its strings in ``sourcedock/i18n.py`` so the application has
no runtime gettext dependency. This tool turns that table into translator- and
Weblate-friendly formats without changing the runtime:

* ``sourcedock.pot`` - a gettext template where ``msgid`` is the stable string
  key and each entry documents the current English text in a comment.
* ``sourcedock.csv`` - ``key,language,text`` rows for spreadsheet or review.

Usage::

    python3 tools/translation_catalog.py --export po
    python3 tools/translation_catalog.py --check
"""

from __future__ import annotations

import argparse
import csv
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from sourcedock.i18n import TRANSLATIONS  # noqa: E402

POT_HEADER = (
    "# SourceDock translation template.\n"
    "# Generated by tools/translation_catalog.py --export.\n"
    "# msgid is the stable string key; the current English text is a comment.\n"
    'msgid ""\n'
    'msgstr ""\n'
    '"Content-Type: text/plain; charset=UTF-8\\n"\n'
    '"Content-Transfer-Encoding: 8bit\\n"\n'
    '"Language: en\\n"\n'
)


def _escape(text: str) -> str:
    return text.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")


def render_pot() -> str:
    tr = TRANSLATIONS["tr"]
    en = TRANSLATIONS["en"]
    lines = [POT_HEADER]
    for key in sorted(en):
        lines.append(f"\n#. english: {_escape(en[key])}")
        lines.append(f"#. turkish: {_escape(tr.get(key, ''))}")
        lines.append(f'msgid "{_escape(key)}"')
        lines.append('msgstr ""')
    lines.append("")
    return "\n".join(lines)


def render_csv() -> str:
    import io

    buffer = io.StringIO()
    writer = csv.writer(buffer)
    writer.writerow(["key", "language", "text"])
    for language in ("tr", "en"):
        for key in sorted(TRANSLATIONS[language]):
            # Keep one physical row per key/language so spreadsheet tools and
            # the integrity test can count records; escape embedded newlines.
            value = TRANSLATIONS[language][key].replace("\r\n", "\\n").replace("\r", "\\n").replace("\n", "\\n")
            writer.writerow([key, language, value])
    return buffer.getvalue()


def export(destination: Path) -> list[Path]:
    destination.mkdir(parents=True, exist_ok=True)
    pot_path = destination / "sourcedock.pot"
    csv_path = destination / "sourcedock.csv"
    pot_path.write_text(render_pot(), encoding="utf-8")
    csv_path.write_text(render_csv(), encoding="utf-8", newline="")
    return [pot_path, csv_path]


def check() -> list[str]:
    problems = []
    tr, en = set(TRANSLATIONS["tr"]), set(TRANSLATIONS["en"])
    if tr - en:
        problems.append(f"missing English keys: {sorted(tr - en)}")
    if en - tr:
        problems.append(f"missing Turkish keys: {sorted(en - tr)}")
    for language in ("tr", "en"):
        for key, value in TRANSLATIONS[language].items():
            if not value.strip():
                problems.append(f"empty {language} value for {key}")
    return problems


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--export", metavar="DIR", help="Write the template and CSV into DIR")
    parser.add_argument("--check", action="store_true", help="Check parity and emptiness")
    args = parser.parse_args()
    if args.export:
        for path in export(Path(args.export)):
            print(f"wrote {path}")
    if args.check:
        problems = check()
        if problems:
            for problem in problems:
                print(problem, file=sys.stderr)
            return 1
        print(f"catalog OK: {len(TRANSLATIONS['en'])} keys, TR/EN parity")
    if not args.export and not args.check:
        parser.print_help()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
